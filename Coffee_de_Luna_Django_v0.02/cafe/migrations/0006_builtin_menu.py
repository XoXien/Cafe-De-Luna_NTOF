def install_catalog(apps, schema_editor):
    db = schema_editor.connection.alias
    Category = apps.get_model('cafe', 'Category')
    Ingredient = apps.get_model('cafe', 'Ingredient')
    Product = apps.get_model('cafe', 'Product')
    RecipeItem = apps.get_model('cafe', 'RecipeItem')
    Movement = apps.get_model('cafe', 'StockMovement')
    categories, ingredients = {}, {}
    for index, name in enumerate(DEFAULT_CATALOG['categories'], 1):
        categories[name] = Category.objects.using(db).get_or_create(name=name, defaults={'sort_order': index})[0]
    for row in DEFAULT_CATALOG['ingredients']:
        ingredient = (Ingredient.objects.using(db).filter(sku=row['sku']).first()
                      or Ingredient.objects.using(db).filter(name=row['name']).first())
        if ingredient and ingredient.unit != row['unit']:
            raise RuntimeError('The existing ingredient uses a different base unit: ' + row['name'])
        if not ingredient:
            opening = Decimal(row['opening_stock'])
            ingredient = Ingredient.objects.using(db).create(name=row['name'], sku=row['sku'], unit=row['unit'],
                storage_type=row['storage_type'], quantity=opening, reorder_level=Decimal(row['reorder_level']),
                cost_per_unit=Decimal(row['cost_per_unit']), notes=row['notes'], is_estimated=True)
            if opening:
                Movement.objects.using(db).create(ingredient=ingredient, quantity=opening, balance_after=opening,
                    kind='opening', note='Built-in menu setup: estimated opening balance; verify by actual count.')
        ingredients[row['key']] = ingredient
    for row in DEFAULT_CATALOG['products']:
        if (Product.objects.using(db).filter(menu_key=row['key']).exists()
                or Product.objects.using(db).filter(name=row['name']).exists()):
            continue
        product = Product.objects.using(db).create(name=row['name'], menu_key=row['key'], menu_name=row['menu_name'],
            variant_label=row['variant_label'], category=categories[row['category']], price=Decimal(row['price']),
            artwork=row['artwork'], description=row['description'], is_add_on=row['is_add_on'],
            customization_type=row.get('customization_type', 'extra'), max_per_drink=row.get('max_per_drink', 1),
            replaces_ingredient=ingredients.get(row.get('replaces_key')), recipe_is_estimated=True,
            recipe_notes='Estimated quantities and ingredient forms. Verify the café recipe before actual service.')
        RecipeItem.objects.using(db).bulk_create([
            RecipeItem(product=product, ingredient=ingredients[key], quantity=Decimal(amount))
            for key, amount in row['recipe'].items()])


